"""Export the committed recorded demo used by the dashboard fallback.

The dashboard opens this file when the free-tier API is asleep or its live-run budget is
exhausted. It is generated from the real deterministic demo seed, not typed by hand, so the
recorded fallback has exactly the same JSON shape as the API.

Run from ``backend/``::

    python -m scripts.export_recorded_demo
"""

from __future__ import annotations

import asyncio
import json
import uuid
from datetime import UTC, datetime
from pathlib import Path
from tempfile import TemporaryDirectory

from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine

import app.storage.models  # noqa: F401  (register tables on Base.metadata)
from app.core.config import BACKEND_ROOT, Settings
from app.services.datasets import get_dataset_detail, list_datasets
from app.services.demo import DEMO_NOTE, seed_demo_data
from app.services.meta import build_meta
from app.services.runs import compare_runs, get_run, get_run_results, get_run_summary, list_runs
from app.storage.base import Base

OUTPUT_PATH = BACKEND_ROOT.parent / "frontend" / "src" / "lib" / "recorded-demo.json"
SCHEMA_VERSION = 1


async def build_export() -> dict[str, object]:
    with TemporaryDirectory(prefix="evalforge-recorded-") as temporary:
        settings = Settings(
            _env_file=None,
            environment="production",
            demo_mode=True,
            database_url="sqlite+aiosqlite:///:memory:",
            data_dir=BACKEND_ROOT / "data",
            qdrant_local_path=Path(temporary) / "qdrant",
            reference_index_on_startup=False,
        )
        engine = create_async_engine("sqlite+aiosqlite:///:memory:")
        try:
            async with engine.begin() as connection:
                await connection.run_sync(Base.metadata.create_all)
            factory = async_sessionmaker(engine, expire_on_commit=False)
            async with factory() as session:
                await seed_demo_data(session, settings)

                meta = await build_meta(session, settings)
                datasets = await list_datasets(session)
                dataset_details: dict[str, object] = {}
                for dataset in datasets:
                    detail = await get_dataset_detail(session, dataset.id)
                    if detail is not None:
                        dataset_details[str(dataset.id)] = detail.model_dump(mode="json")

                page = await list_runs(session, limit=100, offset=0)
                runs: list[dict[str, object]] = []
                run_results: dict[str, object] = {}
                for summary in page.items:
                    run = await get_run(session, summary.id)
                    if run is None:
                        continue
                    summary_payload = await get_run_summary(session, run)
                    runs.append(summary_payload.model_dump(mode="json"))
                    results = await get_run_results(session, run.id, limit=200, offset=0)
                    if results is not None:
                        run_results[str(run.id)] = results.model_dump(mode="json")

                comparisons: dict[str, object] = {}
                if len(runs) >= 2:
                    first_id = str(runs[0]["id"])
                    second_id = str(runs[1]["id"])
                    for baseline_id, candidate_id in (
                        (first_id, second_id),
                        (second_id, first_id),
                    ):
                        comparison = await compare_runs(
                            session,
                            baseline_id=uuid.UUID(baseline_id),
                            candidate_id=uuid.UUID(candidate_id),
                        )
                        comparisons[f"{baseline_id}:{candidate_id}"] = comparison.model_dump(
                            mode="json"
                        )

                return {
                    "schema_version": SCHEMA_VERSION,
                    "generated_at": datetime.now(UTC).isoformat(),
                    "source": (
                        "Generated by backend/scripts/export_recorded_demo.py from the synthetic "
                        "reference corpus with the deterministic mock judge. Latencies and TTFT "
                        f"are simulated. {DEMO_NOTE}"
                    ),
                    "meta": meta.model_dump(mode="json"),
                    "datasets": [dataset.model_dump(mode="json") for dataset in datasets],
                    "dataset_details": dataset_details,
                    "runs": runs,
                    "run_results": run_results,
                    "comparisons": comparisons,
                }
        finally:
            await engine.dispose()


def main() -> None:
    payload = asyncio.run(build_export())
    serialized = json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n"
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(serialized, encoding="utf-8")
    size_kb = len(serialized.encode("utf-8")) / 1024
    print(f"Wrote {OUTPUT_PATH} ({size_kb:.1f} KiB)")


if __name__ == "__main__":
    main()
